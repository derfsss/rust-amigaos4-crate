#!/usr/bin/env python3
"""Write src/sys/weak_globals.rs: a weak NULL definition of every interface
global the sys wrappers declare, except IExec and IDOS.

Run from the repository root after the wrappers change:
    python3 tools/gen-weak-globals.py

Why: a program must define every interface global the crate reads. clib4
defines IExec, IDOS, IUtility, IElf and IClib4 (crtbegin.o); a no-CRT
package's glue defines what it sets. Everything else is a weak NULL here,
which any strong definition (clib4's, a glue file's) replaces, and which
the safe modules treat as "not opened: open it myself" (iface::Slot).
IExec and IDOS are left out: a start-up that does not set them must still
fail to link rather than run with NULL.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WRAPPERS = os.path.join(ROOT, "src", "sys", "wrappers")
OUT = os.path.join(ROOT, "src", "sys", "weak_globals.rs")
EXCLUDE = {"IExec", "IDOS"}

names = set()
for f in sorted(os.listdir(WRAPPERS)):
    if f.endswith(".rs"):
        text = open(os.path.join(WRAPPERS, f), encoding="utf-8").read()
        names.update(re.findall(r"pub static (I[A-Za-z0-9_]+):", text))
names = sorted(names - EXCLUDE)
if len(names) < 100:
    sys.exit("only %d globals found in %s: refusing to write" % (len(names), WRAPPERS))

lines = [
    "//! Weak NULL definitions of the interface globals (generated by",
    "//! tools/gen-weak-globals.py; do not edit).",
    "//!",
    "//! A program need not define the interface globals the crate reads: each",
    "//! here is a weak NULL that a strong definition (clib4's IUtility, IElf",
    "//! and IClib4; a no-CRT glue file's) replaces. NULL makes a safe module",
    "//! open the library itself (iface::Slot). IExec and IDOS are not here: the",
    "//! start-up code (clib4's, or a package's glue) must set them.",
    "",
    "#[cfg(target_os = \"amigaos\")]",
    "core::arch::global_asm!(",
]
for n in names:
    lines.append('    ".section .data.amigaos4_weak.%s,\\"aw\\",@progbits",' % n)
    lines.append('    ".weak %s", ".type %s,@object", ".size %s,4", ".p2align 2",' % (n, n, n))
    lines.append('    "%s:", ".long 0",' % n)
lines.append('    ".previous",')
lines.append(");")
lines.append("")
lines.append("/// The globals given a weak definition above, for tests.")
lines.append("#[cfg_attr(target_os = \"amigaos\", allow(dead_code))]")
lines.append("pub(crate) const WEAK_GLOBALS: &[&str] = &[")
for n in names:
    lines.append('    "%s",' % n)
lines.append("];")
lines.append("")
lines += [
    "#[cfg(test)]",
    "mod tests {",
    "    use super::WEAK_GLOBALS;",
    "",
    "    #[test]",
    "    fn start_up_globals_stay_strong() {",
    "        // A start-up that does not set these must fail to link.",
    "        assert!(!WEAK_GLOBALS.contains(&\"IExec\"));",
    "        assert!(!WEAK_GLOBALS.contains(&\"IDOS\"));",
    "        assert!(WEAK_GLOBALS.len() >= 120, \"{} weak globals\", WEAK_GLOBALS.len());",
    "        assert!(WEAK_GLOBALS.contains(&\"IIntuition\") && WEAK_GLOBALS.contains(&\"IUtility\"));",
    "    }",
    "}",
    "",
]
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("wrote %s: %d globals" % (OUT, len(names)))
